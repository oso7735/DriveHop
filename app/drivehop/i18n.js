let activeLanguage = 'en';

export function configureLanguage(tag) {
  const normalized = String(tag || 'en').toLowerCase();
  activeLanguage = normalized === 'es' || normalized.startsWith('es-') ? 'es' : 'en';
  return activeLanguage;
}


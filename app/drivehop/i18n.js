export function translate(value) {
  if (activeLanguage !== 'es' || typeof value !== 'string' || !value) return value;
  if (Object.prototype.hasOwnProperty.call(ES, value)) return ES[value];
  for (const [pattern, replacement] of ES_RULES) if (pattern.test(value)) return value.replace(pattern, replacement);
  return value;
}

export function translateChildren(children) {
  if (Array.isArray(children)) return children.map(translateChildren);
  return typeof children === 'string' ? translate(children) : children;
}
